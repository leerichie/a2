final Map<String, List<String>> _translations = {
  for (final row in _rows) row.first: row,
};

String translateUi(String languageCode, String input) {
  final index = supportedLanguageCodes.indexOf(languageCode);
  if (index <= 0) return input;
  final exact = _translations[input];
  if (exact != null) return exact[index];
  final replacements = <RegExp, List<String>>{
    RegExp(r'^(\d+) ITEMS$'): [
      r'$1 ELEMENTÓW',
      r'$1 ELEMENTE',
      r'$1 ÉLÉMENTS',
      r'$1 ELEMENTOS',
      r'$1 ELEMENTI',
    ],
    RegExp(r'^(\d+) kcal left for today$'): [
      r'Pozostało dziś $1 kcal',
      r'Heute noch $1 kcal',
      r'Il reste $1 kcal aujourd’hui',
      r'Quedan $1 kcal hoy',
      r'Restano $1 kcal oggi',
    ],
    RegExp(r'^(\d+) daily target$'): [
      r'Dzienny cel: $1',
      r'Tagesziel: $1',
      r'Objectif quotidien : $1',
      r'Objetivo diario: $1',
      r'Obiettivo giornaliero: $1',
    ],
  };
  for (final entry in replacements.entries) {
    if (entry.key.hasMatch(input)) {
      return input.replaceFirst(entry.key, entry.value[index - 1]);
    }
  }
  return input;
}

String ui(material.BuildContext context, String input) =>
    translateUi(material.Localizations.localeOf(context).languageCode, input);

class LText extends material.StatelessWidget {
  const LText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.textDirection,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  });
  final String data;
  final material.TextStyle? style;
  final material.TextAlign? textAlign;
  final material.TextDirection? textDirection;
  final bool? softWrap;
  final material.TextOverflow? overflow;
  final material.TextScaler? textScaler;
  final int? maxLines;
  final String? semanticsLabel;
  final material.TextWidthBasis? textWidthBasis;
  final material.TextHeightBehavior? textHeightBehavior;
  final material.Color? selectionColor;

  @override
  material.Widget build(material.BuildContext context) => material.Text(
    translateUi(material.Localizations.localeOf(context).languageCode, data),
    style: style,
    textAlign: textAlign,
    textDirection: textDirection,
    softWrap: softWrap,
    overflow: overflow,
    textScaler: textScaler,
    maxLines: maxLines,
    semanticsLabel: semanticsLabel,
    textWidthBasis: textWidthBasis,
    textHeightBehavior: textHeightBehavior,
    selectionColor: selectionColor,
  );
}
