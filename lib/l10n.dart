String translateUi(String languageCode, String input) {
  final index = supportedLanguageCodes.indexOf(languageCode);
  if (index <= 0) return input;
  final exact = _translations[input];
  if (exact != null) return exact[index];
  final replacements = <RegExp, List<String>>{
    RegExp(r'^(\d+) ITEMS$'): [
      r'$1 ELEMENTÓW',
      r'$1 ELEMENTE',
      r'$1 ÉLÉMENTS',
      r'$1 ELEMENTOS',
      r'$1 ELEMENTI',
    ],
    RegExp(r'^(\d+) kcal left for today$'): [
      r'Pozostało dziś $1 kcal',
      r'Heute noch $1 kcal',
      r'Il reste $1 kcal aujourd’hui',
      r'Quedan $1 kcal hoy',
      r'Restano $1 kcal oggi',
    ],
    RegExp(r'^(\d+) daily target$'): [
      r'Dzienny cel: $1',
      r'Tagesziel: $1',
      r'Objectif quotidien : $1',
      r'Objetivo diario: $1',
      r'Obiettivo giornaliero: $1',
    ],
    RegExp(r'^(\d+) historical records saved$'): [
      r'Zapisano $1 wpisów historycznych',
      r'$1 historische Einträge gespeichert',
      r'$1 entrées historiques enregistrées',
      r'$1 registros históricos guardados',
      r'$1 record storici salvati',
    ],
    RegExp(r'^(\d+) RECORDS FOUND$'): [
      r'ZNALEZIONO $1 WPISÓW',
      r'$1 EINTRÄGE GEFUNDEN',
      r'$1 ENTRÉES TROUVÉES',
      r'$1 REGISTROS ENCONTRADOS',
      r'$1 RECORD TROVATI',
    ],
    RegExp(r'^Import (\d+) records$'): [
      r'Importuj $1 wpisów',
      r'$1 Einträge importieren',
      r'Importer $1 entrées',
      r'Importar $1 registros',
      r'Importa $1 record',
    ],
    RegExp(r'^This device: (.+)$'): [
      r'To urządzenie: $1',
      r'Dieses Gerät: $1',
      r'Cet appareil : $1',
      r'Este dispositivo: $1',
      r'Questo dispositivo: $1',
    ],
    RegExp(r'^Update check failed: (.+)$'): [
      r'Nie udało się sprawdzić aktualizacji: $1',
      r'Aktualisierungsprüfung fehlgeschlagen: $1',
      r'Échec de la vérification : $1',
      r'Error al buscar actualizaciones: $1',
      r'Controllo aggiornamenti non riuscito: $1',
    ],
  };
  for (final entry in replacements.entries) {
    final match = entry.key.firstMatch(input);
    if (match != null) {
      return entry.value[index - 1].replaceAll(r'$1', match.group(1)!);
    }
  }
  return input;
}

